package com.example.medhead;

import org.junit.jupiter.api.Test;
import org.springframework.boot.actuate.autoconfigure.info.InfoContributorAutoConfiguration;
import org.springframework.boot.actuate.autoconfigure.info.InfoEndpointAutoConfiguration;
import org.springframework.boot.actuate.info.InfoEndpoint;
import org.springframework.boot.autoconfigure.AutoConfigurations;
import org.springframework.boot.autoconfigure.info.ProjectInfoAutoConfiguration;
import org.springframework.boot.test.context.ConfigDataApplicationContextInitializer;
import org.springframework.boot.test.context.runner.ApplicationContextRunner;

import java.util.Map;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.InstanceOfAssertFactories.MAP;

/**
 * Checks that /actuator/info identifies the running build: the Maven version from
 * build-info.properties and the commit from git.properties, both generated by the build.
 */
class ActuatorInfoTest {

	private final ApplicationContextRunner contextRunner = new ApplicationContextRunner()
			.withInitializer(new ConfigDataApplicationContextInitializer())
			.withConfiguration(AutoConfigurations.of(ProjectInfoAutoConfiguration.class,
					InfoContributorAutoConfiguration.class, InfoEndpointAutoConfiguration.class));

	@Test
	void exposesTheBuildVersionAndTheGitCommit() {
		contextRunner.run(context -> {
			Map<String, Object> info = context.getBean(InfoEndpoint.class).info();

			assertThat(info).extractingByKey("build").asInstanceOf(MAP)
					.containsEntry("artifact", "medhead")
					.containsEntry("version", expectedVersion());
			assertThat(info).extractingByKey("git").asInstanceOf(MAP)
					.containsKey("branch")
					.extractingByKey("commit").asInstanceOf(MAP)
					.hasEntrySatisfying("id", id -> assertThat(id).asString().matches("[0-9a-f]{7,40}"));
		});
	}

	private static String expectedVersion() {
		String version = System.getProperty("medhead.expected-version");
		assertThat(version).as("system property medhead.expected-version, set by Maven Surefire").isNotBlank();
		return version;
	}
}
