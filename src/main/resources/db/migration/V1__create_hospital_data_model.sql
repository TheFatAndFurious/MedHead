CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE hospital (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    location geography(Point, 4326) NOT NULL,
    total_beds INTEGER NOT NULL,
    available_beds INTEGER NOT NULL,

    CONSTRAINT ck_hospital_total_beds_non_negative
        CHECK (total_beds >= 0),
    CONSTRAINT ck_hospital_available_beds_valid
        CHECK (available_beds >= 0 AND available_beds <= total_beds)
);

CREATE TABLE specialty (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(100) NOT NULL,
    name VARCHAR(255) NOT NULL,
    specialty_group VARCHAR(255),

    CONSTRAINT uk_specialty_code UNIQUE (code)
);

CREATE TABLE hospital_specialty (
    hospital_id BIGINT NOT NULL,
    specialty_id BIGINT NOT NULL,

    CONSTRAINT pk_hospital_specialty
        PRIMARY KEY (hospital_id, specialty_id),
    CONSTRAINT fk_hospital_specialty_hospital
        FOREIGN KEY (hospital_id)
        REFERENCES hospital (id)
        ON DELETE CASCADE,
    CONSTRAINT fk_hospital_specialty_specialty
        FOREIGN KEY (specialty_id)
        REFERENCES specialty (id)
        ON DELETE RESTRICT
);

CREATE INDEX idx_hospital_location
    ON hospital USING GIST (location);

CREATE INDEX idx_hospital_available_beds
    ON hospital (available_beds)
    WHERE available_beds > 0;

CREATE INDEX idx_hospital_specialty_lookup
    ON hospital_specialty (specialty_id, hospital_id);
